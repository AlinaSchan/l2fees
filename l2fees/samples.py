"""two real mainnet transactions, taken apart. the layer-1 data fee of a rollup depends on the bytes of
the transaction, so the oracles are asked about these bytes: a plain ether transfer and a uniswap swap
through the universal router. both are eip-1559 transactions (type 2) from block 25,982,5xx on
2026-09-15; the hashes are on any explorer, and the live test recomputes them."""
from __future__ import annotations

from dataclasses import dataclass

from . import rlp


@dataclass(frozen=True)
class Sample:
    name: str
    what: str
    hash: str
    block: int
    raw: bytes  # the signed transaction as it went over the wire
    gas_used: int  # from the receipt

    @property
    def fields(self) -> list:
        """chain id, nonce, priority fee, max fee, gas, to, value, data, access list, y parity, r, s."""
        if self.raw[0] != 2:
            raise ValueError("only type-2 transactions are taken apart here")
        return rlp.decode(self.raw[1:])

    @property
    def unsigned(self) -> bytes:
        """the bytes the sender signed: type byte and the first nine fields. the l1 fee oracles want these and add
        the signature's 68 bytes themselves."""
        return b"\x02" + rlp.encode(self.fields[:9])

    @property
    def calldata(self) -> bytes:
        return bytes(self.fields[7])

    @property
    def to(self) -> str:
        return "0x" + bytes(self.fields[5]).hex()

    @property
    def gas_limit(self) -> int:
        return rlp.to_int(self.fields[4])

    @property
    def size(self) -> int:
        return len(self.raw)


